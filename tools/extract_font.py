#!/usr/bin/env python3
"""Extract the X16 KERNAL's PETSCII Upper/Lower charset into a C header.

The charset is public domain (see LICENSE.md in the X16 ROM repository,
https://github.com/X16Community/x16-rom). charset/petscii.s holds 128
Upper/Graphics characters, then 128 Upper/Lower ones; the game switches to
Upper/Lower ($0E) at startup, so that's the set the port draws its text with.
The output is checked in, so building doesn't need the ROM sources.

Usage: extract_font.py X16_ROM/charset/petscii.s src/font_petscii.h
"""
import re
import sys


def main():
    src, out = sys.argv[1:3]
    rows = [int(m.group(1), 2) for m in re.finditer(r"^\.byte\s+%([01]{8})", open(src).read(), re.M)]
    assert len(rows) == 2048, f"expected 2048 rows, got {len(rows)}"
    lower = rows[1024:]
    with open(out, "w") as f:
        f.write("/* Generated by tools/extract_font.py from the X16 ROM's charset/petscii.s\n"
                " * (Upper/Lower set, screen codes $00-$7F). The X16 PETSCII charset is\n"
                " * in the public domain. */\n")
        f.write("#ifndef FONT_PETSCII_H\n#define FONT_PETSCII_H\n\n#include <stdint.h>\n\n")
        f.write("static const uint8_t font_petscii_lower[128 * 8] = {\n")
        for c in range(128):
            f.write("    " + ", ".join(f"0x{v:02x}" for v in lower[c * 8:c * 8 + 8]) + f",  /* ${c:02x} */\n")
        f.write("};\n\n#endif\n")


if __name__ == "__main__":
    main()
